function pickFallback(id: string, pool: string[]): string {
  const hash = id.split("").reduce((acc, c) => acc + c.charCodeAt(0), 0);
  return localImg(pool[hash % pool.length]);
}

export function getActivityImage(a: Activity): string {
  if (a.imageUrl) return a.imageUrl;

  // For live events (no imageUrl), try badge-based thematic image
  if (a.type === "EVENT" && a.badges?.length) {
    const allBadges = a.badges.join(" ");
    for (const { keyword, img } of BADGE_IMAGE_MAP) {
      if (allBadges.toLowerCase().includes(keyword.toLowerCase())) {
        return localImg(img);
      }
    }
    // Category fallback for events
    if (a.category?.some(c => c.toLowerCase().includes("sport"))) return localImg("colle-osservanza.png");
    return pickFallback(a.id, FALLBACKS.EVENT);
  }

  const pool = FALLBACKS[a.type] ?? FALLBACKS.LOCATION;
  return pickFallback(a.id, pool);
}

function addDays(base: string, n: number) {
  const d = new Date(base + "T12:00:00");
  d.setDate(d.getDate() + n);
  return d.toISOString().split("T")[0];
}

